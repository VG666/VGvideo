"""全局共享状态 —— 整个程序唯一一处"跨模块共享的可变数据"

为什么单独成一个文件
    拆分前这些数据是 main.py 的模块级全局,靠 `global xxx` 在各个函数/类之间共享。
    代码按职责拆到多个文件后,`global xxx` 只能改"自己所在文件"的 xxx,
    别的文件看不到改动 —— 所以统一集中到这里,其它模块一律写 `state.xxx`,
    读也是 `state.xxx`,行为与拆分前完全一致,而且"哪些数据是共享的"一眼可见。

分成四块
    一、运行期状态   当前在播什么、开了几个播放器窗口、从哪启动的……
    二、主题与轮播   主题色、轮播进度这类参数
    三、选集与列表   选集按钮 / 海报引用(必须留住引用,否则图片被回收变空白)
    四、控件注册表   原来是 globals()["Left_option_"+str(i)] 这种拼字符串的动态全局,
                    现在统一登记成字典(键就是原来的序号),可读、也不会再拼错名字

约定
    本模块只放数据,不 import 任何 vg* 业务模块,任何模块都能安全引用它。
"""

